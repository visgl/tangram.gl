/** The positions at `count` equal steps on the straight line from `start` to `end`, ends included. */
export function interpolateLine(start: LngLat, end: LngLat, count: number): LngLat[] {
  const positions: LngLat[] = [];
  for (let i = 0; i <= count; i++) {
    const t = i / count;
    positions.push([start[0] + (end[0] - start[0]) * t, start[1] + (end[1] - start[1]) * t]);
  }
  return positions;
}
